#!/usr/bin/env python3
"""Slim an icon theme: ship SVGs once, let the loader scale (v1.0.46).

The released SkynetRedBlack icon tarball carried every SVG at 9 fixed
sizes (16..512) plus the same icons again in Breeze's <context>/<size>
layout and doubled-context dirs (<ctx>/<ctx>/): 55,691 SVG files /
~114 MB uncompressed for ~15k unique icons. KDE/Hicolor loaders scale
SVGs natively from scalable/ dirs (MinSize/MaxSize), so the fixed-size
SVG copies are pure bloat.

This builder reads a full theme dir and writes a slim copy:
  - PNG/JPG (any size): copied verbatim (raster can't rescale losslessly)
  - SVG: ONE master per (context, stem) — preferring scalable/, else
    the largest fixed size — written to scalable/<ctx>/ only. KDE/
    Hicolor loaders scale SVGs from scalable/ dirs at any size
    (MinSize=16/MaxSize=512), exactly like hicolor's scalable/apps.
  - PNG: the largest size only per (context, stem), kept in its native
    size dir (loaders scale raster down cleanly; the old 9x duplicate
    PNG copies — same bytes in every size dir — were pure bloat)
  - index.theme rebuilt from the dirs actually kept (Context/Size/Type
    correct per dir; scalable/ gets MinSize=16/MaxSize=512)
  - icon-theme.cache dropped (regenerated by gtk-update-icon-cache;
    shipping a stale cache is bloat + staleness risk)

Usage: slim-icons.py SRC_DIR DST_DIR [--report]
"""
import pathlib
import re
import shutil
import sys

SIZES = {"8", "12", "16", "20", "22", "24", "28", "32", "36", "48",
         "64", "72", "96", "128", "192", "256", "512"}
CONTEXTS = {"apps", "actions", "status", "panel", "places", "devices",
            "emblems", "mimetypes", "categories", "preferences",
            "applets", "symbolic", "media", "tray", "indicator", "menu",
            "launcher", "kickoff", "system-status"}
CONTEXT_MAP = {"apps": "Applications", "actions": "Actions",
               "status": "Status", "panel": "Status", "places": "Places",
               "devices": "Devices", "emblems": "Emblems",
               "mimetypes": "MimeTypes", "categories": "Categories",
               "preferences": "Applications", "applets": "Applications",
               "symbolic": "Status", "media": "Status", "tray": "Status",
               "indicator": "Status", "menu": "Applications",
               "launcher": "Applications", "kickoff": "Applications",
               "system-status": "Status"}
RASTER_EXTS = {".png", ".jpg", ".jpeg", ".xpm"}
LEAN_SIZES = ("scalable",)


def parse_svg_rel(rel):
    """(ctx, size, stem) for an SVG's theme-relative path, any layout.

    Layouts seen in the wild:
      <size>/<ctx>/file.svg        (canonical)
      scalable/<ctx>/file.svg      (canonical scalable)
      <ctx>/<size>/file.svg        (Breeze layout)
      <ctx>/<ctx>/file.svg         (doubled context, from old scans)
    Returns None for files outside any known context.
    """
    parts = rel.parts
    if len(parts) < 3:
        return None
    stem = parts[-1]
    head = parts[:-1]
    if head[0] in SIZES:
        size, ctx = head[0], head[1] if len(head) > 1 else "apps"
    elif head[0] == "scalable":
        size, ctx = "scalable", head[1] if len(head) > 1 else "apps"
    elif head[0] in CONTEXTS:
        ctx = head[0]
        size = head[1] if len(head) > 1 and head[1] in SIZES else "scalable"
    else:
        return None
    if ctx not in CONTEXTS and ctx != "apps":
        # Unknown context dir (e.g. a theme-private folder): keep as-is
        # under its own name rather than guessing.
        pass
    return ctx, size, stem


def size_rank(size):
    return 10**6 if size == "scalable" else int(size)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    report = "--report" in argv
    argv = [a for a in argv if not a.startswith("--")]
    if len(argv) != 2:
        print(__doc__)
        return 2
    src, dst = pathlib.Path(argv[0]), pathlib.Path(argv[1])
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)

    svg_groups = {}   # (ctx, stem) -> (rank, src_path)
    png_groups = {}   # (ctx, stem) -> (rank, size, src_path, ext)
    raster_count = svg_in = 0
    total_in_bytes = 0

    for p in sorted(src.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(src)
        if rel.name == "icon-theme.cache":
            continue
        if rel.name == "index.theme":
            continue
        total_in_bytes += p.stat().st_size
        if p.suffix.lower() in RASTER_EXTS:
            parsed = parse_svg_rel(rel)
            if parsed is None:
                out = dst / rel
                out.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(p, out)
                raster_count += 1
                continue
            ctx, size, stem = parsed
            # stem here is the full filename (incl. ext) — key on it so
            # foo.png and foo.jpg stay independent.
            rank = size_rank(size)
            key = (ctx, stem)
            if key not in png_groups or rank > png_groups[key][0]:
                png_groups[key] = (rank, size, p)
            raster_count += 1
        elif p.suffix.lower() == ".svg":
            parsed = parse_svg_rel(rel)
            if parsed is None:
                # Unknown layout: preserve verbatim rather than lose it.
                out = dst / rel
                out.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(p, out)
                continue
            ctx, size, stem = parsed
            svg_in += 1
            key = (ctx, stem)
            rank = size_rank(size)
            if key not in svg_groups or rank > svg_groups[key][0]:
                svg_groups[key] = (rank, p)
        else:
            out = dst / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(p, out)

    svg_written = 0
    kept_dirs = set()
    for (ctx, stem), (_rank, master) in sorted(svg_groups.items()):
        dests = [dst / f"{s}" / ctx / stem for s in LEAN_SIZES]
        for d in dests:
            d.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(master, dests[0])
        for d, other in zip(dests[1:], dests):
            shutil.copy(other, d)
        svg_written += len(LEAN_SIZES)
        kept_dirs.update(f"{s}/{ctx}" for s in LEAN_SIZES)

    # Raster: largest size only per (context, stem), native size dir.
    png_written = 0
    for (ctx, stem), (_rank, size, master) in sorted(png_groups.items()):
        out = dst / size / ctx / stem
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(master, out)
        png_written += 1
        kept_dirs.add(f"{size}/{ctx}")

    # Any verbatim-copied files (unknown layouts) live in dirs that
    # must still be registered or the loader ignores them.
    for p in dst.rglob("*"):
        if p.is_file():
            rel = p.relative_to(dst).as_posix()
            if "/" in rel:
                kept_dirs.add(rel.rpartition("/")[0])

    idx_src = src / "index.theme"
    header = ""
    if idx_src.exists():
        text = idx_src.read_text(errors="ignore")
        m = re.search(r"^\[Icon Theme\].*?(?=^\[|\Z)", text, re.M | re.S)
        header = m.group(0).rstrip() if m else "[Icon Theme]\nName=SkynetRedBlack"
        # The [Icon Theme] section carries the OLD Directories= line —
        # strip it so the rebuilt list below is the only one.
        header = re.sub(r"^Directories=.*\n?", "", header, flags=re.M).rstrip()
    else:
        header = "[Icon Theme]\nName=SkynetRedBlack"

    def dir_key(d):
        parts = d.split("/")
        return (parts[0], parts[1] if len(parts) > 1 else "")

    dirs_sorted = sorted(kept_dirs, key=dir_key)
    out = [header, f"Directories={','.join(dirs_sorted)}"]
    for d in dirs_sorted:
        size, ctx = d.split("/")
        if size == "scalable":
            out.append(f"\n[{d}]\nContext={CONTEXT_MAP.get(ctx, 'Applications')}"
                       f"\nSize=48\nType=Scalable\nMinSize=16\nMaxSize=512")
        else:
            out.append(f"\n[{d}]\nContext={CONTEXT_MAP.get(ctx, 'Applications')}"
                       f"\nSize={size}\nType=Fixed")
    (dst / "index.theme").write_text("\n".join(out) + "\n")

    if report:
        total_out = sum(p.stat().st_size for p in dst.rglob("*") if p.is_file())
        n_out = sum(1 for p in dst.rglob("*") if p.is_file())
        n_in = sum(1 for p in src.rglob("*") if p.is_file())
        print(f"input:  {n_in} files, {total_in_bytes/1e6:.1f} MB")
        print(f"output: {n_out} files, {total_out/1e6:.1f} MB")
        print(f"  raster: {raster_count} in -> {png_written} written "
              f"(largest size only each)")
        print(f"  svg: {svg_in} in -> {len(svg_groups)} unique (ctx,stem) "
              f"-> {svg_written} written (scalable/ only)")
        print(f"  dirs kept: {len(dirs_sorted)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
